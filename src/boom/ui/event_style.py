"""
==============================================================================
Boom 離線使用者介面 - 事件辨識標籤與固定配色策略 (event_style.py)
==============================================================================

【檔案定位】
提供跨視訊疊圖、地圖航跡標記與座標卡片的一致性事件識別樣式（標籤編號與配色）。

【核心函式】
- `event_label(event_id) -> str`: 產生如 "S01", "S02" 的煙霧事件標準編號。
- `event_color(event_id) -> tuple[int, int, int]`: 依據事件 ID 分配穩定的高對比 BGR 外框顏色。
==============================================================================
"""

def event_label(event_id):
    return f"S{event_id:02d}"


def event_color(event_id):
    palette = ((70, 170, 255), (220, 190, 70), (180, 110, 240),
               (110, 210, 100), (220, 140, 100), (100, 120, 255))
    return palette[int(event_id) % len(palette)]
